#!/usr/bin/env python3
"""
Convert *_jpg.h JPEG byte-array headers to pre-decoded RGB565 pixel headers.

Each output header contains a const uint16_t[] array in byte-swapped RGB565
format (SPI wire order) so it can be blitted directly via canvas.pushImage()
with zero runtime heap allocation.

Usage: python3 convert_to_rgb565.py
Requires: pip install Pillow
"""

import re
import io
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow not found — run: pip3 install Pillow")

TARGET_W = 168
TARGET_H = 168

# Matches how drawJpg placed images: 70% scale (168x168) centred, shifted up 13px
# canvas.drawJpg(data, len, 0, -13, 240, 240, 0, 0, 0.7, 0.7, middle_center)
# → top-left corner at ((240-168)/2, (240-168)/2 - 13) = (36, 23)
DRAW_X = (240 - TARGET_W) // 2      # 36
DRAW_Y = (240 - TARGET_H) // 2 - 13  # 23


def parse_c_byte_array(text: str) -> bytes:
    """Extract byte values from a C hex byte array literal."""
    return bytes(int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]{2}', text))


def to_rgb565_spi(img: Image.Image) -> list[int]:
    """
    Convert a PIL Image to byte-swapped RGB565 uint16_t values.

    M5GFX canvas sprites store pixels in SPI wire order (bytes swapped vs
    standard RGB565) so DMA can feed them directly to the display controller.
    pushImage() with swap_bytes=false (the default) copies them as-is.
    """
    img = img.convert('RGB').resize((TARGET_W, TARGET_H), Image.LANCZOS)
    out = []
    for r, g, b in img.getdata():
        rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        # byte-swap so the value is in SPI wire order
        swapped = ((rgb565 & 0xFF) << 8) | (rgb565 >> 8)
        out.append(swapped)
    return out


def write_header(out_path: Path, varname: str, pixels: list[int]) -> None:
    lines = [f'// Auto-generated by convert_to_rgb565.py — do not edit',
             f'// {TARGET_W}x{TARGET_H} RGB565 (byte-swapped, SPI wire order)',
             f'// Draw at canvas.pushImage({DRAW_X}, {DRAW_Y}, {TARGET_W}, {TARGET_H}, {varname});',
             f'',
             f'const uint16_t {varname}[] = {{']
    row: list[str] = []
    for i, px in enumerate(pixels):
        row.append(f'0x{px:04x}')
        if len(row) == 12 or i == len(pixels) - 1:
            lines.append('  ' + ', '.join(row) + ',')
            row = []
    lines.append('};')
    lines.append('')
    out_path.write_text('\n'.join(lines))


def main() -> None:
    images_dir = Path(__file__).parent
    h_files = sorted(images_dir.glob('*_jpg.h'))

    if not h_files:
        sys.exit('No *_jpg.h files found in ' + str(images_dir))

    for h_file in h_files:
        stem = h_file.stem                    # e.g. "back_jpg"
        name = stem.replace('_jpg', '')       # "back"
        varname = f'{name}_rgb565'            # "back_rgb565"
        out_file = images_dir / f'{varname}.h'

        print(f'{h_file.name}  →  {out_file.name}', end='  ', flush=True)

        jpeg_bytes = parse_c_byte_array(h_file.read_text())
        img = Image.open(io.BytesIO(jpeg_bytes))
        orig_w, orig_h = img.size
        pixels = to_rgb565_spi(img)

        write_header(out_file, varname, pixels)
        print(f'({orig_w}x{orig_h} → {TARGET_W}x{TARGET_H}, {len(pixels)*2} bytes)')

    print(f'\nDone. {len(h_files)} images converted.')
    print(f'Each blits to: canvas.pushImage({DRAW_X}, {DRAW_Y}, {TARGET_W}, {TARGET_H}, <name>_rgb565);')


if __name__ == '__main__':
    main()
